List<Topic> _topics(
    String subjectId, String sectionId, String examType, List<String> titles) {
  return titles
      .asMap()
      .entries
      .map(
        (e) => Topic(
          id: '${subjectId}_${e.key}',
          title: e.value,
          subjectId: subjectId,
          sectionId: sectionId,
          examType: examType,
          status: TopicStatus.notStarted,
        ),
      )
      .toList();
}
